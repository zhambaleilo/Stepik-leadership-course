export const PRESS = /я требую|ко мне в кабинет|объяснись|отчитайся|почему опять|ты опять|ты всегда|ты никогда|как ты мог|сколько раз можно повторять|хватит|ты должен|ты обязан|не потерплю|кто ты такой|соберись|возьми себя|ты вообще\s+(ничего\s+не\s+)?понимаешь|кто разрешил|как ты себе позволяешь|ты в своём уме|сам подумай|ну ты даёшь|чтобы ты наконец|берега попутал|попутал|ты чего|ты что ли|как не стыдно/i;

export const KILL = /(^|[^a-zа-яё])(идиот|хам|дурак|дебил|ничтожество|неудачник|клоун|заткнись|тварь|урод)(?![a-zа-яё])|(^|[^a-zа-яё])(уволю|последнее предупреждение|лишу премии|выгоню|ты конченый)/i;

export const INSULT = /(^|[^a-zа-яё])(хам|дурак|идиот|дебил|ничтожество|клоун|заткнись|замолчи|тварь|урод|сволочь|хамло|позор|стыдно|чушь|бред|офигел|обалдел|попутал)(?![a-zа-яё])|(^|[^a-zа-яё])(совсем там|ты нормальн|ты чего|ты что ли)/i;

// РАСШИРЕННЫЙ OFFER: ловит предложения/идеи/просьбы сотрудника,
// включая ленивые формулировки ("возьму неделю за свой счёт", "доделаю тесты сам")
export const OFFER = /может(,\s*я)?|может\s+быть|может\s+стоит|давайте\s+(я|мы)|предлагаю|хочу\s+попросить|я\s+могу\s+(взять|сделать|поработать|доделать|закончить|остаться)|возьму\s+на\s+себя|возьму\s+(неделю|отпуск|отгул|выходной|больничный|за\s+свой)|сделаю\s+(сам|сама)|доделаю\s+(сам|сама)|поработаю\s+(сам|сама|в\s+выходные|дома)|пойду\s+в\s+(отпуск|отгул|больничный)|уйду\s+на\s+(больничный|отпуск|отгул)|попрошу\s+(помощь|помощи)|а\s+если\s+я|я\s+бы\s+мог|мог\s+бы\s+(я|сделать|поработать|взять)|если\s+позволите/i;

export const EMOTION = /чувствую\s+(себя\s+)?(неудачник|устал|тяжело|выгорел)|мне\s+(тяжело|плохо|страшно|больно|невыносимо)|нет\s+сил|не\s+могу|не\s+вывожу|на\s+пределе|я\s+всё|устал|вымотался|не\s+справляюсь/i;

export function hasToxicity(text) {
  return PRESS.test(text) || INSULT.test(text) || KILL.test(text);
}

export function hasOffer(text) {
  return OFFER.test(text);
}

export function hasEmotion(text) {
  return EMOTION.test(text);
}
